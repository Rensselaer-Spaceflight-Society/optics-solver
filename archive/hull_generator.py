class HullPoint:
    def __init__(self, pos: CoordinateVector, *adjs: HullPoint):
        self.position = pos
        self.adjacent_pts = {
            adj_pt.id: adj_pt for adj_pt in adjs
        }
        self.id = uuid4()

    def __call__(self):
        return self

    def get_neighbor_tetrahedra(self, centerpoint: CoordinateVector):
        # get neighbor's first adjacent neighbor (in arbitrary order, it doesn't really matter)
        tetra_verts = []
        completed_tetra = set() if completed_tetra is None else completed_tetra
        for n_id, n in self.adjacent_pts.items():
            for n2_id, n2 in n.adjacent_pts.items():
                if(n2_id not in self.adjacent_pts):
                    continue
                tetra_base = frozenset((self.id, n_id, n2_id))
                if(tetra_base in completed_tetra):
                    continue
                completed_tetra.add(tetra_base)
                tetra_verts.append((centerpoint, self.position, n.position, n2.position))
        return tetra_verts
            

    def get_adj(self):
        return self.adjacent_pts

